CLAUSE_SPLIT_RE = re.compile(r"\s+and\s+(?=SYM\()")


def split_clauses(sentence):
    """Split a sentence into clauses on ' and ' when the next clause starts
    with a math-span placeholder - e.g. 'A is a group and A is a subgroup
    of B' becomes two clauses. This deliberately only splits before SYM(
    (i.e. before a new subject), so 'the join of H1 and H2' or similar
    phrases inside a single clause are left alone."""
    return CLAUSE_SPLIT_RE.split(sentence)


def _find_antecedent(sentences, idx, sym):
    """Nearest preceding sentence (within this scope segment) that mentions
    `sym` inside a math placeholder. Returns the sentence text, or None."""
    needle = re.compile(r"SYM\([^)]*\b" + re.escape(sym) + r"\b[^)]*\)")
    for k in range(idx - 1, -1, -1):
        if needle.search(sentences[k]):
            return sentences[k].strip()
    return None


def extract_declarations(text, patterns, equation_patterns=None):
    """Return list of dicts: {sym, role, rel, meaning, sentence, confidence,
    scope}. `scope` is a tuple of enclosing MediaWiki header titles, e.g.
    ('Proof', 'Example 1'), or () for content before any header."""
    results = []

    for scope_path, seg_text in split_into_scopes(text):
        seg_begin = len(results)
        seg_text = strip_wiki_markup(seg_text)
        desugared, spans = desugar(seg_text)
        sentences = SENTENCE_SPLIT_RE.split(desugared)

        for sent_idx, sent in enumerate(sentences):
          for clause in split_clauses(sent):
            sent_matches = []
            # Verbless declarations only fire in a declaration context
            # (Given / To prove / Suppose / "the following are equivalent
            # for ..."), where "a <descriptor> SYM(x)" really is
            # introducing x rather than just mentioning it in passing.
            active = list(patterns)
            if (DECLARATION_CONTEXT_RE.match(sent.strip())
                    or EXISTENTIAL_RE.search(sent)):
                active = active + VERBLESS_PATTERNS
            for pat in active:
                # Patterns are written with a literal "SYM(" for readability;
                # turn that into the escaped "SYM\(" the regex engine needs.
                working = pat["regex"].replace("SYM(", r"SYM\(")
                # finditer (not search): a single clause can still carry
                # more than one pattern match (e.g. bare is-a + is-a-of
                # both matching overlapping text) - collect all, dedup below.
                for m in re.finditer(working, clause, flags=re.IGNORECASE):
                    gd = m.groupdict()

                    # Object-position guard: if the matched subject symbol is
                    # immediately preceded by a preposition ("...of nonzero
                    # elements of SYM(L) is the center of..."), it is the
                    # object of that preposition, not the sentence's subject.
                    # Attributing the predicate to it produces a confidently
                    # wrong declaration ("L is the center of K^*" when the
                    # text says L^* is). Patterns that anchor on a head noun
                    # (subj_role) locate the subject correctly and are exempt.
                    if "subj_role" not in gd:
                        preceding = clause[:m.start()].rstrip()
                        if re.search(r"\b(?:" + _REL_PREP_ALT + r")\s*$", preceding, re.IGNORECASE):
                            continue

                    sym = normalize_symbol(gd.get("sym", ""))
                    role = (gd.get("role") or "").strip()
                    rel = normalize_symbol(gd.get("rel", "")) if gd.get("rel") else None
                    prep = (gd.get("prep") or "of").strip()
                    meaning = pat["template"].format(sym=sym, role=role, rel=rel, prep=prep)

                    # "of A with B" (e.g. "wreath product of the group of
                    # prime order with W") is a two-argument construction,
                    # NOT the "prep a <descriptor> X" idiom this pattern is
                    # meant for (e.g. "subgroup of a finite group G"). If
                    # the captured rel_role swallowed a trailing connector
                    # word (with/and/by/...), that descriptor is unreliable
                    # - but the primary fact "sym relates to rel" (role and
                    # rel come from separate, unaffected capture groups) is
                    # still fine and worth keeping at reduced confidence:
                    # dropping it entirely would make W (the referent)
                    # invisible to UNDECLARED_REFERENT rather than correctly
                    # flagged as "referenced but never itself declared".
                    descriptor_unreliable = pat.get("also_declares_rel") and _SECOND_ARG_RE.search(gd.get("rel_role") or "")
                    if descriptor_unreliable:
                        confidence = "low"
                    else:
                        confidence = pat.get("confidence", "high")

                    # Attachment ambiguity: the subject symbol is separated
                    # from its verb by prepositional phrases that themselves
                    # contain symbols ("the multiplicative group L^* OF
                    # nonzero elements OF L is the center of K^*"). We now
                    # resolve this correctly, but a reader skimming the
                    # sentence can misattach it the same way the parser
                    # originally did - so surface it as an advisory to add
                    # commas or parentheses. This is a readability warning,
                    # not a correctness error: the meaning below is right.
                    #
                    # If the author HAS set the modifier off with commas or
                    # parentheses, the subject is already unmistakable to a
                    # reader and the advisory is suppressed - otherwise the
                    # tool would keep nagging about a sentence that has
                    # already been fixed as it asked.
                    mid_text = gd.get("mid") or ""
                    # Strip SYM(...) placeholders before testing for author
                    # punctuation - the placeholders carry their own
                    # parentheses, which would otherwise look like the
                    # commas/parens we are asking the author to add.
                    mid_bare = re.sub(r"SYM\([^)]*\)", " ", mid_text)
                    already_punctuated = bool(re.search(r"[,()]", mid_bare))
                    ambiguous = bool(
                        pat.get("also_declares_subj_role")
                        and re.search(r"SYM\(", mid_text)
                        and not already_punctuated
                    )

                    sent_matches.append({
                        "sym": sym,
                        "role": role,
                        "rel": rel,
                        "meaning": meaning,
                        "sentence": sent.strip(),
                        "confidence": confidence,
                        "scope": scope_path,
                        "pos": desugared.find(sent[:40]) if sent else 0,
                        "kind": classify_declaration_kind(sent, clause),
                        "is_restatement": bool(RESTATEMENT_MARKERS_RE.match(sent.strip())),
                        "is_goal": bool(GOAL_CONTEXT_RE.match(sent.strip())
                                        or EXISTENTIAL_RE.search(sent)),
                        # For a restatement, record the nearest preceding
                        # sentence that mentions this symbol. We often can't
                        # PARSE that antecedent into a meaning (it may
                        # characterize the symbol implicitly, e.g. by placing
                        # it in a chain "H < K < G"), but we can point at it
                        # so a reviewer can compare the two by hand. Without
                        # this, a restatement whose antecedent is implicit
                        # looks like a lone characterization and is never
                        # surfaced for review.
                        "antecedent": _find_antecedent(sentences, sent_idx, sym),
                        "ambiguous_attachment": ambiguous,
                        "span": (m.start(), m.end()),
                    })
                    # Some patterns (e.g. "...of a finite group G") declare
                    # BOTH symbols in one match: the primary sym, and the
                    # relation target via its own inline descriptor. Emit a
                    # second declaration for the latter, anchored to the
                    # same span so dedup treats it as part of the same
                    # match - but only when the descriptor itself is
                    # trustworthy (see descriptor_unreliable above).
                    if pat.get("also_declares_subj_role") and gd.get("subj_role"):
                        subj_role = gd["subj_role"].strip()
                        sent_matches.append({
                            "sym": sym,
                            "role": subj_role,
                            "rel": None,
                            "meaning": f"{sym} is a {subj_role}",
                            "sentence": sent.strip(),
                            "confidence": pat.get("confidence", "high"),
                            "scope": scope_path,
                            "kind": "binding",
                            # Derived from apposition ("the group of prime
                            # order p"), which is a weaker inference than an
                            # explicit binding: the descriptor may actually
                            # qualify the symbol ("order p") rather than
                            # name it. If this conflicts with an existing
                            # binding, that's more likely a reading
                            # ambiguity than a real rebinding.
                            "from_apposition": True,
                            "span": (m.start(), m.end()),
                        })

                    if pat.get("also_declares_rel") and gd.get("rel_role") and not descriptor_unreliable:
                        rel_role = gd["rel_role"].strip()
                        sent_matches.append({
                            "sym": rel,
                            "role": rel_role,
                            "rel": None,
                            "meaning": f"{rel} is a {rel_role}",
                            "sentence": sent.strip(),
                            "confidence": pat.get("confidence", "high"),
                            "scope": scope_path,
                            # An inline descriptor ("...of a finite group G")
                            # introduces G, so it counts as a binding - but
                            # it's an apposition, so the descriptor may be
                            # qualifying the symbol ("the group of prime
                            # order p") rather than naming it. Conflicts get
                            # reported as ambiguity, not redefinition.
                            "kind": "binding",
                            "from_apposition": True,
                            "span": (m.start(), m.end()),
                        })

            # Dedup within this clause: when two matches overlap and share
            # the same symbol, keep only the wider (more specific) one,
            # e.g. "is-a-of" over bare "is-a" for the same span, since the
            # narrower one is almost always a partial submatch of the same
            # underlying declaration, not a second distinct one.
            sent_matches.sort(key=lambda r: -(r["span"][1] - r["span"][0]))
            kept = []
            for r in sent_matches:
                s0, e0 = r["span"]
                overlaps_kept_wider = any(
                    r["sym"] == k["sym"] and not (e0 <= k["span"][0] or s0 >= k["span"][1])
                    for k in kept
                )
                if not overlaps_kept_wider:
                    kept.append(r)
            for r in kept:
                del r["span"]
            results.extend(kept)

        # Second pass: definitional equations living entirely inside one
        # math span, e.g. "B = \mathbb{F}_p[H]" - these have no surrounding
        # English for the sentence-level patterns to anchor on.
        #
        # An equation in a CONCLUSION sentence ("thus d = 1", "we conclude
        # K = L") is a derived result, not a definition: treating it as one
        # makes a proof's own conclusion look like a redefinition of the
        # symbol it constrains. We locate each span's enclosing sentence to
        # decide. Likewise a bare-numeral RHS ("d = 1") is essentially never
        # a definition in running proof text.
        for content in spans:
            enclosing = ""
            marker = f"SYM({content.strip()})"
            for s in sentences:
                if marker in s:
                    enclosing = s
                    break

            if CONCLUSION_MARKERS_RE.search(enclosing):
                continue

            for pat in (equation_patterns or EQUATION_PATTERNS):
                m = re.match(pat["regex"], content.strip())
                if not m:
                    continue
                gd = m.groupdict()
                sym = normalize_symbol(gd.get("sym", ""))
                rhs = (gd.get("rhs") or "").strip()
                if re.fullmatch(r"-?\d+", rhs):
                    break  # "d = 1" - a constraint/result, not a definition
                meaning = pat["template"].format(sym=sym, role="", rel=None, rhs=rhs)
                results.append({
                    "sym": sym,
                    "role": "",
                    "rel": None,
                    "meaning": meaning,
                    "sentence": enclosing.strip() or f"${content.strip()}$",
                    "confidence": pat.get("confidence", "medium"),
                    "scope": scope_path,
                    "pos": desugared.find(marker),
                    "kind": classify_declaration_kind(enclosing or ""),
                    "is_restatement": bool(
                        RESTATEMENT_MARKERS_RE.match((enclosing or "").strip())),
                })
                break

        # Equations are collected in a second pass over the segment, so
        # without re-sorting they always appear after every prose sentence
        # regardless of where they actually occur. That inverts the order of
        # a definition and a later derived property, and REDEFINITION
        # compares against the most recent PRIOR meaning - so the inversion
        # manufactures conflicts that the text does not contain.
        results[seg_begin:] = sorted(results[seg_begin:],
                                     key=lambda r: r.get("pos", 0))

    return results


