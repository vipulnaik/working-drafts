# 1. Declaration templates (configurable)
#
# Each pattern is applied to a *desugared* sentence where every math span
# has been replaced by a placeholder token \x01<content>\x02, so the regex
# only has to deal with the surrounding English, not LaTeX escaping.
#
# Capture groups:
#   sym   - the symbol being declared (required)
#   role  - short role label, e.g. "group", "subgroup", "homomorphism"
#   rel   - the related symbol, if any (e.g. the G in "subgroup of G")
# --------------------------------------------------------------------------

# Prepositions that connect a symbol to its "container"/context in a
# declaration sentence ("subgroup OF G", "map FROM G", "series IN G",
# "element FROM S", "generated BY S"). Configurable so a project can add
# domain-specific ones without touching the regexes below.
# Prepositions that connect a symbol to its "container"/context in a
# declaration sentence ("subgroup OF G", "map FROM G", "series IN G",
# "element FROM S"). Configurable so a project can add domain-specific
# ones without touching the regexes below. Deliberately excludes "by":
# in math prose "by" is ambiguous - sometimes a clean single-argument
# connector ("normalized by G") but often the second argument of a
# two-object construction ("quotient of G by N", "wreath product of A
# by B") where treating it like "of"/"from" would misparse the relation
# the same way "with" did (see SECOND_ARG_CONNECTORS below). Safer to
# not match "by" here at all than to sometimes match it wrong.
REL_PREPOSITIONS = ["of", "from", "in", "over", "on", "into", "onto"]

# Prepositions that, when they appear where a "with"-style second-argument
# connector would, signal a two-argument construction ("wreath product OF
# A WITH B") rather than the "descriptor + target" idiom ("subgroup OF a
# finite group G"). Matches on these are skipped rather than mis-parsed -
# see the "also_declares_rel" skip logic in extract_declarations.
SECOND_ARG_CONNECTORS = ["with", "and", "by"]

_REL_PREP_ALT = "|".join(REL_PREPOSITIONS)
_SECOND_ARG_RE = re.compile(
    r"\b(?:" + "|".join(SECOND_ARG_CONNECTORS) + r")\b", re.IGNORECASE
)

# A "binding" INTRODUCES a symbol ("Let L be the center of K", "define
# C_K(g) to be...", "we denote by K^* the multiplicative group"). A
# "property assertion" states something TRUE about an already-introduced
# symbol ("L is a field", "L is an additive subgroup of K"). Only bindings
# can conflict with each other - a proof legitimately derives many
# simultaneously-true properties of the same object, and treating each new
# property as a redefinition of the last is the single largest source of
# false positives on real proof pages.
# Restatement markers: a sentence that re-expresses something already
# stated ("Equivalently, A = F_p[G] x G ...", "In symbols, H = <H_1,H_2>",
# "In other words, K is the largest normal subgroup...") describes the SAME
# object a second way. Treating those as fresh bindings makes every
# "here it is in symbols" sentence look like a redefinition of the thing it
# is restating - a very common shape in mathematical writing.
RESTATEMENT_MARKERS_RE = re.compile(
    r"^\s*(?:equivalently|in\s+symbols|in\s+other\s+words|that\s+is|namely|"
    r"i\.e\.|explicitly|more\s+precisely|put\s+differently|"
    r"stated\s+differently|alternatively)\b",
    re.IGNORECASE,
)

BINDING_MARKERS_RE = re.compile(
    r"^\s*(?:let\b|define\b|set\b|put\b|we\s+denote\b|denote\b|write\b|"
    r"suppose\b|assume\b|consider\b|take\b|for\s+an?\b)",
    re.IGNORECASE,
)

# Conclusion markers: an equation appearing in a sentence like "we conclude
# d = 1" or "thus K = L" is a DERIVED RESULT, not a definition of d or K.
# Without this, a proof's own conclusion registers as a redefinition of
# the symbol it constrains.
CONCLUSION_MARKERS_RE = re.compile(
    r"\b(?:conclude|thus|hence|therefore|so\s+that|forces?|must\s+have|"
    r"it\s+follows|we\s+get|we\s+obtain|implies|show(?:s|ed)?\s+that|"
    r"this\s+gives|equality\s+holds)\b",
    re.IGNORECASE,
)


GOAL_CONTEXT_RE = re.compile(
    r"^\s*(?:to\s+prove|we\s+must\s+show|we\s+want\s+to\s+show|claim)\b",
    re.IGNORECASE,
)

EXISTENTIAL_RE = re.compile(r"\bthere\s+exists?\b", re.IGNORECASE)


def classify_declaration_kind(sentence, clause=None):
    """Return 'binding' or 'assertion' for a declaration found in this
    sentence. Bindings are what REDEFINITION compares; assertions merely
    accumulate."""
    probe = clause if clause is not None else sentence
    # A restatement re-expresses an existing object, so it can never be a
    # fresh binding no matter what verb it uses. Checked against the whole
    # sentence, since the marker leads the sentence while the declaration
    # may sit in a later clause.
    if RESTATEMENT_MARKERS_RE.match(sentence.strip()):
        return "assertion"
    # A goal ("To prove: there exists a group K such that ...") states what
    # is to be established, and an existential names a witness that a later
    # step will construct. Neither binds the symbol, so a subsequent "Let K
    # be ..." is instantiation, not redefinition.
    if GOAL_CONTEXT_RE.match(sentence.strip()) or EXISTENTIAL_RE.search(sentence):
        return "assertion"
    if BINDING_MARKERS_RE.match(probe.strip()):
        return "binding"
    return "assertion"

# Verbless declarations. Groupprops proof pages introduce symbols with no
# verb at all - "Given: A group G, a normal subgroup H of G", "The
# following are equivalent for a subgroup H of a group G". Every
# "X is a Y" pattern misses these, so G and K end up looking permanently
# undeclared on essentially every proof page.
#
# Applied ONLY inside a declaration context (below), because the bare
# shape "a <descriptor> SYM(x)" is far too common in ordinary prose
# ("the direct factors of V", "a homomorphic image of V") to trust on
# its own.
DECLARATION_CONTEXT_RE = re.compile(
    r"^\s*(?:given|to\s+prove|suppose|assume|consider|let|"
    r"the\s+following\s+are\s+equivalent|we\s+are\s+given)\b",
    re.IGNORECASE,
)

