def similar(a, b, threshold=0.82):
    return difflib.SequenceMatcher(None, a.lower(), b.lower()).ratio() >= threshold


GIVEN_COMPONENT_RE = re.compile(
    r"(?:an?|the)\s+(?P<role>[\w -]+?)\s+SYM\((?P<sym>[^)]+)\)"
    r"(?:\s+(?:of|with|having)\s+(?P<qualifier>[\w -]+?))?(?=\s*[,.;:]|$)",
    re.IGNORECASE,
)

# Words carrying no distinguishing content, so useless as a citation key.
_STOPWORDS = {"a", "an", "the", "of", "with", "size", "group", "set", "element"}


def given_components(given_text):
    """Split a Given block into its independent hypotheses.

    "A division ring K of finite size" is a CONJUNCTION: K is a division
    ring, and K is finite. Both are load-bearing and are typically consumed
    at different steps. Treating the Given as atomic makes partial citation
    invisible - the column looks used because the other component was cited.

    Returns [(symbol, description, keyword)] where keyword is the
    distinguishing word to look for in a 'Given data used' cell.
    """
    desugared, _ = desugar(strip_wiki_markup(given_text))
    out = []
    for m in GIVEN_COMPONENT_RE.finditer(desugared):
        sym = normalize_symbol(m.group("sym"))
        role = (m.group("role") or "").strip()
        qual = (m.group("qualifier") or "").strip()

        if role:
            key = [w for w in role.lower().split() if w not in _STOPWORDS]
            if key:
                out.append((sym, f"{sym} is a {role}", key[-1]))
        if qual:
            key = [w for w in qual.lower().split() if w not in _STOPWORDS]
            if key:
                out.append((sym, f"{sym} is {qual}", key[0]))
    return out


# Objects that force the construction to be infinite. If a page's
# constructions live over these, no finite instantiation exists, and tools
# that compute orders or emit GAP are structurally inapplicable - not merely
# short of data. Saying so is more useful than emitting a scaffold that can
# never run or an order arithmetic over quantities that are all infinite.
INFINITE_MARKERS = [
    (r"\\R\b|\\mathbb\{R\}", "the reals"),
    (r"\\mathbb\{Q\}", "the rationals"),
    (r"\\mathbb\{C\}", "the complex numbers"),
    (r"\bpositive reals\b", "the positive reals"),
    # Deliberately NOT included: "finitary" and a bare "infinite". Both
    # appear in pages that DO have finite instantiations - the
    # potentially-characteristic page mentions the finitary alternating
    # group only as a recipe for the infinite case, while its own smallest
    # example has order 14400. Only objects that are inherently infinite
    # count here.
]


def find_infinite_domain(text):
    """Report markers that the page's constructions are inherently infinite.

    Returns list of (severity, line_no, message). Advisory: it does not
    mean the page is wrong, it means finite computational verification is
    not available for it.
    """
    hits = []
    for pat, what in INFINITE_MARKERS:
        m = re.search(pat, text)
        if m:
            line = text.count("\n", 0, m.start()) + 1
            hits.append((what, line))
    if not hits:
        return []
    what = ", ".join(sorted({w for w, _ in hits}))
    line = min(l for _, l in hits)
    return [("INFINITE_DOMAIN", line,
             f"constructions on this page involve {what}; no finite "
             f"instantiation exists, so order arithmetic and GAP scaffolds "
             f"are structurally inapplicable rather than merely incomplete")]


def find_uncited_givens(text):
    """Advisory: a section states a Given, contains a tabular proof with a
    'Given data used' column, and no row cites anything in that column.

    The tabular format makes a structural commitment ordinary prose does
    not: the column exists to record where a hypothesis is consumed, so an
    empty cell asserts the step does not depend on it. An entirely empty
    column means the point where the Given first enters the argument was
    never recorded.

    Deliberately whole-table, not per-row. Downstream steps inherit a
    hypothesis through the 'Previous steps used' chain, so flagging every
    row that transitively depends on the Given would push toward redundant
    citations the step-reference chain already carries. What is missing is
    the single row where the Given is FIRST consumed.

    Returns list of (severity, line_no, message).
    """
    issues = []
    lines = text.split("\n")

    state = {
        "section": None, "given_seen": False, "given_text": [],
        "col_index": None, "n_rows": 0, "n_cited": 0,
        "cells_text": [], "table_line": 0,
    }

    def flush():
        st = state
        if not (st["given_seen"] and st["col_index"] is not None and st["n_rows"]):
            return
        if not st["n_cited"]:
            issues.append((
                "UNCITED_GIVEN", st["table_line"],
                f"section {st['section']!r} states a Given, but its "
                f"'Given data used' column is empty in all {st['n_rows']} rows - "
                f"the step where the hypothesis is first consumed is unrecorded"
            ))
            return

        # The column IS used, but a Given may be a CONJUNCTION of several
        # independent hypotheses ("a division ring K of finite size"), each
        # consumed at a different step. Check each component separately -
        # otherwise citing one makes the others look accounted for, and
        # dropping a citation becomes invisible.
        blob = " ".join(st["cells_text"]).lower()
        comps = given_components(" ".join(st["given_text"]))
        if len(comps) > 1:
            for sym, desc, key in comps:
                if key not in blob:
                    issues.append((
                        "UNCITED_GIVEN", st["table_line"],
                        f"section {st['section']!r}: the Given includes "
                        f"{desc!r}, but no row cites it in 'Given data used' "
                        f"(looked for {key!r}). Other parts of the Given ARE "
                        f"cited, so the column is in use - this component "
                        f"alone is unaccounted for"
                    ))

    for i, raw in enumerate(lines, 1):
        line = raw.strip()

        m = HEADER_RE.match(line)
        if m:
            flush()
            state.update({"section": m.group(2).strip(), "given_seen": False,
                          "given_text": [], "col_index": None,
                          "n_rows": 0, "n_cited": 0, "cells_text": []})
            continue

        if re.search(r"'''\s*Given\s*'''", line) or re.match(r"^Given\s*:", line, re.I):
            state["given_seen"] = True
            state["given_text"].append(line)

        if line.startswith("!"):
            headers = [h.strip().lstrip("!").strip()
                       for h in re.split(r"\s*!!\s*", line.lstrip("!"))]
            for idx, h in enumerate(headers):
                if re.search(r"given\s+data", h, re.IGNORECASE):
                    state["col_index"] = idx
                    state["table_line"] = i
            state["n_rows"] = state["n_cited"] = 0
            state["cells_text"] = []
            continue

        if line.startswith("|") and not line.startswith("|-") and not line.startswith("|}"):
            if state["col_index"] is None:
                continue
            cells = re.split(r"\s*\|\|\s*", line.lstrip("|"))
            state["n_rows"] += 1
            ci = state["col_index"]
            if ci < len(cells) and cells[ci].strip():
                state["n_cited"] += 1
                state["cells_text"].append(cells[ci])

    flush()
    return issues


def find_multiple_characterizations(declarations):
    """Group symbols that are characterized more than one way within a
    scope, so a reviewer (human or LLM) can confirm the characterizations
    actually agree.

    This is NOT an error check. Describing one object several ways is
    normal and often good writing. The failure mode it targets is the
    *underdetermined* restatement: a second description that picks out a
    different object than the first because a qualifying clause was
    dropped. Such a sentence is grammatically fine, introduces no new
    symbol, and conflicts with nothing - so every other check here passes
    it. Only a reader who knows the mathematics can settle it, which is
    exactly why it's surfaced as a prompt rather than a verdict.

    Returns a list of dicts, highest-priority first:
        {sym, scope, priority, characterizations: [{meaning, sentence,
         kind, is_restatement}]}

    priority is "high" when the characterizations are explicitly linked -
    same sentence, or one flagged by a restatement marker ("in other
    words", "equivalently"). Those are asserted to be equivalent, so a
    mismatch is a real defect rather than two independent true facts.
    Everything else is "normal": likely just accumulated properties.
    """
    groups = {}
    for d in declarations:
        groups.setdefault((d["sym"], d["scope"]), []).append(d)

    out = []
    for (sym, scope), decls in groups.items():
        # Collapse near-identical wordings; they aren't two characterizations.
        distinct = []
        for d in decls:
            if not any(similar(d["meaning"], k["meaning"]) for k in distinct):
                distinct.append(d)
        # A restatement whose antecedent couldn't be parsed into a meaning
        # still deserves review: show the raw antecedent sentence alongside
        # it. This is the case where the first characterization is implicit
        # (a symbol placed in a chain, say) rather than a parseable "X is a Y".
        antecedents = [d for d in distinct
                       if d.get("is_restatement") and d.get("antecedent")]
        if len(distinct) < 2 and not antecedents:
            continue

        # "high" requires an explicit restatement marker. Same-sentence
        # co-occurrence is too weak on its own: one long explanatory
        # sentence can mention a symbol several ways incidentally
        # ("we don't even use that H is a subgroup of G ... H is a subset
        # of G ...") without asserting those are equivalent.
        linked = any(d.get("is_restatement") for d in distinct)
        if len(distinct) < 2:
            linked = True  # restatement with an unparsed antecedent
        out.append({
            "sym": sym,
            "scope": list(scope),
            "priority": "high" if linked else "normal",
            "characterizations": [
                {
                    "meaning": d["meaning"],
                    "sentence": d["sentence"],
                    "kind": d.get("kind", "binding"),
                    "is_restatement": bool(d.get("is_restatement")),
                }
                for d in distinct
            ],
            # Raw sentences a restatement is restating, where we could not
            # parse them into a meaning. Unparsed on purpose - the reviewer
            # compares them by eye.
            "antecedents": sorted({d["antecedent"] for d in antecedents}),
        })

    out.sort(key=lambda g: (g["priority"] != "high", g["sym"]))
    return out


def format_characterizations(groups, indent=""):
    """Human-readable rendering of find_multiple_characterizations()."""
    lines = []
    for g in groups:
        tag = "VERIFY-EQUIVALENCE" if g["priority"] == "high" else "characterizations"
        n = len(g["characterizations"]) + len(g.get("antecedents", []))
        lines.append(f"{indent}[{tag}] '{g['sym']}' "
                     f"[{scope_label(tuple(g['scope']))}] "
                     f"is characterized {n} ways:")
        for i, c in enumerate(g["characterizations"], 1):
            mark = " (restatement)" if c["is_restatement"] else ""
            lines.append(f"{indent}    {i}. {c['meaning']}{mark}")
            lines.append(f"{indent}       from: \"{c['sentence'][:100]}\"")
        for a in g.get("antecedents", []):
            lines.append(f"{indent}    ~. (restating, unparsed) \"{a[:100]}\"")
        if g["priority"] == "high":
            lines.append(f"{indent}    -> these are asserted to be equivalent; "
                         f"confirm they pick out the same object")
    return "\n".join(lines)


def dedupe_declarations(declarations):
    """Collapse declarations that are identical in (sym, meaning, scope).
    The same math span or sentence often recurs across table cells, and
    re-reporting each copy inflates both the draft table and the issue
    list without adding information. Keeps first occurrence order."""
    seen = set()
    out = []
    for d in declarations:
        key = (d["sym"], d["meaning"], d["scope"])
        if key in seen:
            continue
        seen.add(key)
        out.append(d)
    return out


def check_consistency(declarations, approved_table):
    """Return list of (severity, message) tuples.

    Scope-aware: a symbol re-used with a different meaning is only flagged
    as REDEFINITION if the two declarations occur in *related* scopes
    (same section or table row, or one nested inside the other). Sibling
    scopes - two independent '===Example...===' subsections, or two steps
    of a tabular proof - are NOT compared against each other, since reuse
    there is normal, not a slip.

    Kind-aware: only 'binding' declarations ("Let L be the center of K")
    are compared for REDEFINITION. 'assertion' declarations ("L is a
    field", "L is an additive subgroup of K") state properties that are
    simultaneously true, so they accumulate rather than conflict.

    Each declaration is compared against the MOST RECENT related binding
    only, not every prior one - pairwise comparison turns n declarations
    of one symbol into O(n^2) messages saying substantially the same thing.
    """
    declarations = dedupe_declarations(declarations)

    issues = []
    last_meaning = {}  # sym -> (scope, meaning) of most recent declaration of any kind
    declared_syms = []  # list of (scope, sym) for every symbol declared so far, in order
    reported_undeclared = set()

    # Symbols declared together in the same sentence (e.g. "N is a subgroup
    # of a group M" declares N and M in one match) count as simultaneous,
    # not sequential - without this, whichever of the pair happens to be
    # processed first would wrongly see the other as "not yet declared".
    same_sentence_syms = {}
    for d in declarations:
        key = (d["scope"], d["sentence"])
        same_sentence_syms.setdefault(key, set()).add(d["sym"])

    for d in declarations:
        sym, meaning, scope = d["sym"], d["meaning"], d["scope"]

        # UNDECLARED_REFERENT: this declaration explains sym in terms of
        # another symbol ("B is a subgroup of C"), but that other symbol
        # has never itself been declared anywhere in a related scope -
        # it's only ever appeared as someone else's "of X" target, never
        # as a subject in its own right. Checked against declarations seen
        # so far (textual order) PLUS anything declared in this same
        # sentence (simultaneous declarations, see same_sentence_syms above).
        if d.get("rel") and d["rel"] != sym:
            rel_declared = any(
                s == d["rel"] and scope_visible_from(rscope, scope)
                for rscope, s in declared_syms
            )
            if not rel_declared:
                rel_declared = d["rel"] in same_sentence_syms.get((scope, d["sentence"]), set())
            if not rel_declared and d["rel"] not in reported_undeclared:
                # Report each never-declared symbol ONCE. A symbol used
                # throughout a survey page produces one finding, not one per
                # use: fourteen copies of "G is never declared" is a single
                # fact rendered unreadable.
                reported_undeclared.add(d["rel"])
                uses = sum(1 for x in declarations if x.get("rel") == d["rel"])
                extra = (f" (used this way {uses} times on the page)"
                         if uses > 1 else "")
                issues.append((
                    "UNDECLARED_REFERENT",
                    f"'{d['rel']}' is used to describe '{sym}' (\"{meaning}\") "
                    f"[{scope_label(scope)}] but '{d['rel']}' itself is never "
                    f"declared{extra} -- (\"{d['sentence'][:70]}\")",
                ))

        # AMBIGUOUS_ATTACHMENT (advisory): the declaration was resolved
        # correctly, but the sentence separates its subject from its verb
        # with prepositional phrases containing other symbols. A reader can
        # misattach the predicate to the nearer symbol just as a naive
        # parser does. Suggest punctuation; the meaning itself is fine.
        if d.get("ambiguous_attachment"):
            issues.append((
                "AMBIGUOUS_ATTACHMENT",
                f"'{sym}' is separated from its verb by phrases containing other "
                f"symbols; read as \"{meaning}\" [{scope_label(scope)}]. Consider "
                f"commas or parentheses to make the subject unmistakable "
                f"-- (\"{d['sentence'][:70]}\")",
            ))

        # SELF_REFERENCE: symbol declared in terms of itself, e.g.
        # "A is a subgroup of A". Always worth a human look regardless
        # of scope - this is a deterministic, high-confidence catch.
        if d.get("rel") and d["rel"] == sym:
            issues.append((
                "SELF_REFERENCE",
                f"'{sym}' is declared in terms of itself: \"{meaning}\" "
                f"[{scope_label(scope)}] -- (\"{d['sentence'][:70]}\")",
            ))

        # REDEFINITION: fires when a symbol is re-BOUND to a meaningfully
        # different meaning within a related scope. The *current*
        # declaration must be a binding (property assertions accumulate and
        # never conflict), but it is compared against the most recent prior
        # meaning of either kind - re-binding a symbol that already had an
        # established meaning is exactly the error worth catching, whether
        # that meaning came from an earlier binding or an assertion.
        if d.get("kind", "binding") == "binding":
            prior = last_meaning.get(sym)
            if prior is not None:
                prior_scope, prior_meaning = prior
                if scopes_related(prior_scope, scope) and not similar(prior_meaning, meaning):
                    if d.get("from_apposition"):
                        # The conflicting reading came from apposition ("the
                        # group of prime order p"), where the descriptor may
                        # be qualifying the symbol rather than naming it.
                        # Report the ambiguity, not a redefinition - but do
                        # report it, since a reader can misread it too.
                        issues.append((
                            "AMBIGUOUS_ATTACHMENT",
                            f"'{sym}' already means \"{prior_meaning}\", but the phrasing "
                            f"here also reads as \"{meaning}\" [{scope_label(scope)}]. "
                            f"Likely the descriptor qualifies '{sym}' rather than naming "
                            f"it; consider rewording -- (\"{d['sentence'][:70]}\")",
                        ))
                    else:
                        issues.append((
                            "REDEFINITION",
                            f"'{sym}' previously meant \"{prior_meaning}\" "
                            f"[{scope_label(prior_scope)}], now re-bound as \"{meaning}\" "
                            f"[{scope_label(scope)}] -- (\"{d['sentence'][:70]}\")",
                        ))
        # A goal or existential ("To prove: there exists a group K ...")
        # names a witness rather than fixing a meaning, so it must not
        # become the baseline a later construction is compared against -
        # otherwise every proof that builds its witness looks like a
        # redefinition of the thing it was asked to produce.
        if not d.get("is_goal"):
            last_meaning[sym] = (scope, meaning)

        # DRIFT: not present in the human-approved table at all, or present
        # only under an unrelated scope.
        approved = approved_table.get(sym)
        if approved is None:
            issues.append((
                "DRIFT",
                f"'{sym}' declared as \"{meaning}\" [{scope_label(scope)}] "
                f"but not in approved table -- (\"{d['sentence'][:70]}\")",
            ))
        else:
            relevant = [
                a for a in approved
                if scopes_related(tuple(a.get("scope", [])), scope)
            ]
            candidates = relevant or approved  # fall back to all if scope info missing/unrelated
            approved_meanings = [a["meaning"] for a in candidates]
            if not any(similar(meaning, am) for am in approved_meanings):
                issues.append((
                    "DRIFT",
                    f"'{sym}' now means \"{meaning}\" [{scope_label(scope)}] but "
                    f"approved table (same-scope entries) says {approved_meanings} "
                    f"-- (\"{d['sentence'][:70]}\")",
                ))

        declared_syms.append((scope, sym))

    # POSSIBLE_ALIAS (soft): different symbols, near-identical meaning text,
    # restricted to related scopes - otherwise every page-wide reuse of
    # "is a subgroup of" phrasing floods the output with noise.
    #
    # Ultra-generic roles are excluded: on a group theory page most symbols
    # are "a group" or "a subgroup", so matching on those says nothing about
    # whether two symbols are actually the same object.
    GENERIC_ROLES = {
        "group", "subgroup", "set", "element", "field", "ring", "space",
        "map", "function", "number", "integer", "prime",
    }
    items = [(d["sym"], d["meaning"], d["scope"], (d.get("role") or "").strip().lower())
             for d in declarations]
    for i in range(len(items)):
        for j in range(i + 1, len(items)):
            sym_a, mean_a, scope_a, role_a = items[i]
            sym_b, mean_b, scope_b, role_b = items[j]
            if role_a in GENERIC_ROLES and role_b in GENERIC_ROLES:
                continue
            if (sym_a != sym_b
                    and scopes_related(scope_a, scope_b)
                    and similar(mean_a, mean_b, threshold=0.9)):
                # Show BOTH meanings. Printing only one hides the case that
                # matters most: two descriptions that are nearly identical
                # but differ in one token (T_1 vs T_2) - exactly where a
                # copy-paste slip would live. Identical text and a one-token
                # difference need different responses from the reader.
                if mean_a == mean_b:
                    detail = f"both mean \"{mean_a}\""
                else:
                    detail = (f"mean nearly the same thing:\n"
                              f"        {sym_a}: {mean_a}\n"
                              f"        {sym_b}: {mean_b}")
                issues.append((
                    "POSSIBLE_ALIAS",
                    f"'{sym_a}' [{scope_label(scope_a)}] and '{sym_b}' "
                    f"[{scope_label(scope_b)}] {detail} -- "
                    f"confirm this is intentional (e.g. two distinct subgroups)",
                ))

    return issues


