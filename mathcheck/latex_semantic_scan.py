MATH_SPAN_RE = re.compile(
    r"(?<!\\)\$\$(.+?)(?<!\\)\$\$"
    r"|(?<!\\)\$(.+?)(?<!\\)\$"
    r"|\\\((.+?)\\\)"
    # <math>...</math> matched case-insensitively: real pages contain
    # typos like "<matH>" / "</matH>", and a case-sensitive pattern
    # silently SKIPS those spans rather than reporting them, which is
    # the worst failure mode for a checker. See find_malformed_math_tags()
    # for the companion check that reports them as an issue.
    r"|<[Mm][Aa][Tt][Hh]>(.+?)</[Mm][Aa][Tt][Hh]>",
    re.DOTALL,
)


def find_malformed_math_tags(text):
    """Report structural problems with <math> tags. Returns a list of
    (severity, line_no, message).

    Two severities, because they matter very differently:

      MATH_TAG_CASE      - cosmetic only. MediaWiki matches the tag
                           case-insensitively, so '<matH>' renders exactly
                           like '<math>'. Worth tidying when you're already
                           editing, but it is invisible to readers and must
                           not gate a pipeline.

      MALFORMED_MATH_TAG - genuinely broken: empty, unbalanced, or crossed
                           delimiters. These change what renders AND corrupt
                           span detection downstream, turning prose into
                           phantom variables.
    """
    issues = []
    for m in re.finditer(r"</?[Mm][Aa][Tt][Hh]>", text):
        tag = m.group(0)
        canonical = tag.lower()
        if tag != canonical:
            line = text.count("\n", 0, m.start()) + 1
            issues.append(("MATH_TAG_CASE", line,
                           f"non-canonical math tag {tag!r} (should be "
                           f"{canonical!r}) - cosmetic, does not affect rendering"))

    # Empty spans: <math></math> contains nothing, so MATH_SPAN_RE (which
    # requires at least one character) skips past it and instead matches
    # from this opening tag to the NEXT closing tag - swallowing the prose
    # in between and turning ordinary letters into phantom variables.
    for m in re.finditer(r"<[Mm][Aa][Tt][Hh]>\s*</[Mm][Aa][Tt][Hh]>", text):
        line = text.count("\n", 0, m.start()) + 1
        issues.append(("MALFORMED_MATH_TAG", line,
                       "empty math span (<math></math>) - will corrupt "
                       "span detection for the rest of the line"))

    # Swallowed prose: a matched span whose contents still contain a math
    # tag means the delimiters are crossed somewhere (unclosed tag, stray
    # tag). The parse downstream is meaningless until it's fixed.
    for m in MATH_SPAN_RE.finditer(text):
        content = next((g for g in m.groups() if g is not None), "")
        if re.search(r"</?[Mm][Aa][Tt][Hh]>", content):
            line = text.count("\n", 0, m.start()) + 1
            issues.append(("MALFORMED_MATH_TAG", line,
                           "math span contains a nested/stray math tag - "
                           f"delimiters are crossed: {content.strip()[:50]!r}"))

    opens = len(re.findall(r"<[Mm][Aa][Tt][Hh]>", text))
    closes = len(re.findall(r"</[Mm][Aa][Tt][Hh]>", text))
    if opens != closes:
        issues.append(("MALFORMED_MATH_TAG", 0,
                       f"unbalanced math tags: {opens} opening, {closes} closing"))
    return issues

SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+(?=[A-Z\\$])")


def strip_wiki_markup(text):
    """Remove MediaWiki structural markup that isn't prose, so it can't
    break mid-sentence pattern matching. Applied BEFORE math-span
    desugaring, so it must not touch <math>...</math> contents."""
    # Protect math spans first so markup-stripping regexes can't reach inside them.
    protected = []

    def stash(m):
        protected.append(m.group(0))
        return f"\x00{len(protected) - 1}\x00"

    text = MATH_SPAN_RE.sub(stash, text)

    # [[fact about::X;| ]][[X]]  or  [[uses::X]]: -> drop annotation links entirely
    text = re.sub(r"\[\[[a-zA-Z ]+::[^\]]*\]\]", "", text)
    # [[Page name|Display text]] -> Display text ; [[Page name]] -> Page name
    text = re.sub(r"\[\[([^\]|]+)\|([^\]]*)\]\]", lambda m: m.group(2) or m.group(1), text)
    text = re.sub(r"\[\[([^\]]+)\]\]", r"\1", text)
    # '' italics / ''' bold -> strip markers, keep text
    text = re.sub(r"'{2,3}", "", text)
    # <pre>...</pre> is verbatim code, not prose. Left in, GAP snippets get
    # spliced into declaration sentences and quoted back as evidence.
    text = re.sub(r"<pre>.*?</pre>", " ", text, flags=re.DOTALL | re.IGNORECASE)
    # {{template}} -> drop entirely (e.g. {{tabular proof format}})
    text = re.sub(r"\{\{[^{}]*\}\}", "", text)
    # <toggledisplay>...</toggledisplay> and similar inline wiki HTML ->
    # keep the CONTENTS (it's real explanatory prose, often where the
    # actual declarations live) but drop the tags themselves.
    text = re.sub(r"</?toggledisplay>", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"</?(?:small|sup|sub|br|ref)\s*/?>", " ", text, flags=re.IGNORECASE)
    # Table markup: {| ... |} wrapper lines, |- row separators, ! header
    # cells. Cell separators (|| and leading |) become sentence-ending
    # periods so adjacent cells don't run together into one bogus
    # "sentence" spanning several columns.
    text = re.sub(r"^\s*\{\|.*$", "", text, flags=re.MULTILINE)   # table open
    text = re.sub(r"^\s*\|\}.*$", "", text, flags=re.MULTILINE)   # table close
    text = re.sub(r"^\s*\|-.*$", "", text, flags=re.MULTILINE)    # row separator
    text = re.sub(r"^\s*!.*$", "", text, flags=re.MULTILINE)      # header row
    text = re.sub(r"\|\|", ". ", text)                            # cell separator
    text = re.sub(r"^[ \t]*\|\s*", "", text, flags=re.MULTILINE)  # leading cell pipe
    # == Headers == -> drop the line entirely (not prose)
    text = re.sub(r"^\s*=+.*=+\s*$", "", text, flags=re.MULTILINE)
    # leading list markers (* # :) -> drop, keep rest of line
    text = re.sub(r"^[ \t]*[*#:]+\s*", "", text, flags=re.MULTILINE)

    # Restore math spans
    def restore(m):
        return protected[int(m.group(1))]

    text = re.sub(r"\x00(\d+)\x00", restore, text)
    return text


def desugar(text):
    """Replace math spans with SYM(<content>) placeholders; return
    (desugared_text, list_of_original_spans_in_order)."""
    spans = []

    def repl(m):
        content = next(g for g in m.groups() if g is not None)
        spans.append(content.strip())
        return f"SYM({content.strip()})"

    return MATH_SPAN_RE.sub(repl, text), spans


HEADER_RE = re.compile(r"^(=+)\s*(.*?)\s*=+\s*$")


def split_into_scopes(text):
    """Split raw page text into (scope_path, segment_text) chunks using
    MediaWiki '== Header ==' lines to build a nesting path, e.g. a
    subsection under Proof gets scope_path ('Proof', 'Example 1').

    Table rows ('|-' separators) additionally open a nested scope, since
    in the tabular-proof format each numbered step is a self-contained
    unit: symbols are routinely re-described per step ("L is a field",
    "L is the center of K") and comparing across steps produces noise
    the same way comparing across sibling ===Example=== sections did.

    This runs BEFORE strip_wiki_markup/desugar - it only understands
    header and row syntax, nothing else.
    """
    segments = []
    stack = []  # list of (level, title)
    current_lines = []
    row_counter = [0]
    in_row = [False]

    def flush():
        if any(l.strip() for l in current_lines):
            path = tuple(title for _, title in stack)
            if in_row[0]:
                path = path + (f"row {row_counter[0]}",)
            segments.append((path, "\n".join(current_lines)))
        current_lines.clear()

    for line in text.split("\n"):
        stripped = line.strip()
        m = HEADER_RE.match(stripped)
        if m:
            flush()
            in_row[0] = False
            row_counter[0] = 0
            level = len(m.group(1))
            title = m.group(2).strip()
            while stack and stack[-1][0] >= level:
                stack.pop()
            stack.append((level, title))
        elif stripped.startswith("|-"):
            # Row separator: close the previous row's scope, open the next.
            flush()
            row_counter[0] += 1
            in_row[0] = True
        elif stripped.startswith("|}"):
            # Table closed - back to plain section scope.
            flush()
            in_row[0] = False
            row_counter[0] = 0
        else:
            current_lines.append(line)
    flush()
    return segments


def scopes_related(a, b):
    """True if scope path `a` and `b` are the same, or one is an ancestor
    of the other (nested), so a declaration in one is visible from the
    other. False for siblings/cousins - e.g. two independent '===Example'
    subsections under the same '==Proof==' are NOT related, since each
    is its own self-contained construction and reusing a variable name
    across them is normal, not a redefinition."""
    n = min(len(a), len(b))
    return a[:n] == b[:n]


def _is_row(component):
    return component.startswith("row ")


def scope_visible_from(declared_scope, use_scope):
    """Visibility is WIDER than relatedness. Two rows of one tabular proof
    are siblings for redefinition purposes (each step restates properties
    of the same objects, and comparing across steps is noise) - but a proof
    is sequential, so a symbol introduced in step 4 IS legitimately in
    scope at step 9. Treat earlier rows of the same table as visible;
    otherwise fall back to ordinary relatedness."""
    if (declared_scope and use_scope
            and _is_row(declared_scope[-1]) and _is_row(use_scope[-1])
            and declared_scope[:-1] == use_scope[:-1]):
        try:
            return int(declared_scope[-1][4:]) <= int(use_scope[-1][4:])
        except ValueError:
            return True
    return scopes_related(declared_scope, use_scope)


def scope_label(scope_path):
    return " > ".join(scope_path) if scope_path else "(page top)"


def normalize_symbol(raw):
    """Strip outer whitespace and common no-op wrapping so 'G' and ' G '
    and '{G}' collapse to the same key. Deliberately shallow - reuses the
    same notion of 'atom' as latex_var_scan.py would, but kept standalone
    here to avoid a hard dependency between the two scripts."""
    s = raw.strip()
    s = re.sub(r"^\{(.*)\}$", r"\1", s)
    return s


